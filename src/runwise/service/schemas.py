"""
Pydantic v2 schemas defining the HTTP request and response contracts
for the Runwise Production Agent Service.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Liveness probe response model."""

    status: str = Field(default="ok", description="Service operational status")
    version: str = Field(default="0.1.0", description="Semantic version of the Runwise service")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Current UTC timestamp in ISO-8601 format",
    )


class TokenUsageSchema(BaseModel):
    """Token consumption breakdown for an agent run."""

    prompt_tokens: int = Field(default=0, ge=0, description="Tokens consumed by user & system prompts")
    completion_tokens: int = Field(default=0, ge=0, description="Tokens generated by model completions")
    total_tokens: int = Field(default=0, ge=0, description="Sum of prompt and completion tokens")


class AgentRunRequest(BaseModel):
    """
    Input payload for POST /v1/agent/run.
    """

    prompt: str = Field(
        ...,
        min_length=1,
        max_length=4096,
        description="The customer's input query or message",
        examples=["I want to check the status of my order ORD-101."],
    )
    session_id: str = Field(
        default_factory=lambda: f"sess_{uuid.uuid4().hex[:12]}",
        description="Unique session identifier. If omitted, a fresh session is allocated.",
    )
    customer_id: str | None = Field(
        default=None,
        description="Optional customer identifier to authenticate the user session.",
        examples=["CUST-001"],
    )
    task_id: str = Field(
        default="adhoc_api_run",
        description="Evaluation or operational tracking identifier.",
    )

    auto_route: bool = Field(
        default=False,
        description="Whether to use the cost-aware AutoRouter to dynamically select between Flash and Pro based on prompt complexity.",
    )
    mode: str = Field(
        default="conversation",
        description="Execution mode: 'scenario' (isolated sandbox + grading) or 'conversation' (multi-turn).",
    )


    @field_validator("prompt")
    @classmethod
    def validate_non_whitespace_prompt(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Prompt must not be empty or contain only whitespace.")
        return stripped


class GraderStatusEnum(str, Enum):
    PASS = "PASS"
    FAIL = "FAIL"
    NOT_APPLICABLE = "NOT_APPLICABLE"
    NOT_EVALUATED = "NOT_EVALUATED"


class GraderDetailSchema(BaseModel):
    status: GraderStatusEnum = GraderStatusEnum.NOT_APPLICABLE
    reason_code: str | None = None
    message: str | None = None


class EvaluationSummarySchema(BaseModel):
    overall_status: GraderStatusEnum = GraderStatusEnum.NOT_EVALUATED
    task_completion: GraderDetailSchema = Field(default_factory=GraderDetailSchema)
    policy_compliance: GraderDetailSchema = Field(default_factory=GraderDetailSchema)
    groundedness: GraderDetailSchema = Field(default_factory=GraderDetailSchema)
    explanation: str = "Deterministic evaluation summary."


class SanitizedToolCall(BaseModel):
    id: str
    tool_name: str
    arguments: dict[str, Any] = Field(default_factory=dict)
    status: str = Field(default="success", description="'success' or 'error'")
    result_data: dict[str, Any] | None = None
    error_message: str | None = None


class SanitizedTimelineEvent(BaseModel):
    seq: int
    event_type: str = Field(
        description="REQUEST_RECEIVED, ROUTING_DECISION, MODEL_INVOCATION, TOOL_EXECUTION, FINAL_RESPONSE, or EVALUATION"
    )
    timestamp_iso: str
    summary: str
    details: dict[str, Any] = Field(default_factory=dict)


class ScenarioRunRequest(BaseModel):
    scenario_id: str = Field(
        ...,
        description="Server-controlled scenario identifier (e.g. scenario_order_lookup, scenario_address_update).",
    )
    auto_route: bool = Field(default=True, description="Whether to route dynamically via AutoRouter")


class AgentRunResponse(BaseModel):
    """
    Output payload returned from POST /v1/agent/run and POST /v1/demo/scenarios/run.
    """

    session_id: str = Field(..., description="Active session identifier")
    response: str = Field(..., description="Final textual answer generated by the agent")
    exit_reason: str = Field(..., description="Reason for agent termination (e.g. final_response, max_steps)")
    complexity_score: float | None = Field(
        default=None,
        description="Assigned prompt complexity score in [0.0, 1.0] if auto_route was enabled.",
    )
    routing_reason: str | None = Field(
        default=None,
        description="Explanation of the model routing decision.",
    )
    step_count: int = Field(..., ge=0, description="Total reasoning/tool turns executed")
    tokens: TokenUsageSchema = Field(default_factory=TokenUsageSchema, description="Token consumption summary")
    latency_ms: float = Field(..., ge=0.0, description="Total execution time in milliseconds")
    model: str = Field(..., description="LiteLLM model identifier used for generation")
    prompt_version: str = Field(default="v1.0", description="Version of the system prompt template applied")
    variant: str = Field(default="stable", description="Traffic routing variant ('stable' or 'canary')")
    features_detected: list[str] = Field(
        default_factory=list,
        description="Regex or semantic features detected by auto-router",
    )
    cost_usd: float | None = Field(
        default=None,
        description="Calculated USD cost of token consumption",
    )
    is_replay: bool = Field(
        default=False,
        description="Server-controlled flag indicating empirical replay",
    )
    tool_calls: list[SanitizedToolCall] = Field(
        default_factory=list,
        description="Sanitized allowlisted tool call details",
    )
    events: list[SanitizedTimelineEvent] = Field(
        default_factory=list,
        description="Sanitized execution trace timeline events",
    )
    evaluation: EvaluationSummarySchema | None = Field(
        default=None,
        description="Deterministic 4-tier grader evaluation results",
    )

