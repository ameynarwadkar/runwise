"""
Pydantic v2 schemas defining the HTTP request and response contracts
for the Runwise Production Agent Service.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Liveness probe response model."""

    status: str = Field(default="ok", description="Service operational status")
    version: str = Field(default="0.1.0", description="Semantic version of the Runwise service")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Current UTC timestamp in ISO-8601 format",
    )


class TokenUsageSchema(BaseModel):
    """Token consumption breakdown for an agent run."""

    prompt_tokens: int = Field(default=0, ge=0, description="Tokens consumed by user & system prompts")
    completion_tokens: int = Field(default=0, ge=0, description="Tokens generated by model completions")
    total_tokens: int = Field(default=0, ge=0, description="Sum of prompt and completion tokens")


class AgentRunRequest(BaseModel):
    """
    Input payload for POST /v1/agent/run.
    """

    prompt: str = Field(
        ...,
        min_length=1,
        max_length=4096,
        description="The customer's input query or message",
        examples=["I want to check the status of my order ORD-101."],
    )
    session_id: str = Field(
        default_factory=lambda: f"sess_{uuid.uuid4().hex[:12]}",
        description="Unique session identifier. If omitted, a fresh session is allocated.",
    )
    customer_id: str | None = Field(
        default=None,
        description="Optional customer identifier to authenticate the user session.",
        examples=["CUST-001"],
    )
    task_id: str = Field(
        default="adhoc_api_run",
        description="Evaluation or operational tracking identifier.",
    )

    @field_validator("prompt")
    @classmethod
    def validate_non_whitespace_prompt(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Prompt must not be empty or contain only whitespace.")
        return stripped


class AgentRunResponse(BaseModel):
    """
    Output payload returned from POST /v1/agent/run.
    """

    session_id: str = Field(..., description="Active session identifier")
    response: str = Field(..., description="Final textual answer generated by the agent")
    exit_reason: str = Field(..., description="Reason for agent termination (e.g. final_response, max_steps)")
    step_count: int = Field(..., ge=0, description="Total reasoning/tool turns executed")
    tokens: TokenUsageSchema = Field(default_factory=TokenUsageSchema, description="Token consumption summary")
    latency_ms: float = Field(..., ge=0.0, description="Total execution time in milliseconds")
    model: str = Field(..., description="LiteLLM model identifier used for generation")
    prompt_version: str = Field(default="v1.0", description="Version of the system prompt template applied")
    variant: str = Field(default="stable", description="Traffic routing variant ('stable' or 'canary')")
