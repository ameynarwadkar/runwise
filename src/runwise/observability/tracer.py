"""
OpenTelemetry Tracing and Arize Phoenix Observability Integration.

Provides non-invasive trace instrumentation:
- Zero overhead if PHOENIX_ENABLED is false.
- Launches local Phoenix UI server (http://localhost:6006) when active.
- Records parent agent trial spans and nested tool-dispatch child spans.
"""

from __future__ import annotations

import json
import os
import sys
from contextlib import contextmanager
from typing import Any, Generator

_PHOENIX_SESSION = None


class _FilterInternalSpansProcessor:
    """
    OpenTelemetry SpanProcessor wrapper that drops internal server spans
    generated by Phoenix's FastAPI/GraphQL server, ensuring only agent evaluation
    traces appear in the Phoenix UI.
    """

    def __init__(self, target: Any) -> None:
        self._target = target

    def on_start(self, span: Any, parent_context: Any = None) -> None:
        if hasattr(self._target, "on_start"):
            self._target.on_start(span, parent_context=parent_context)

    def _on_ending(self, span: Any) -> None:
        if hasattr(self._target, "_on_ending"):
            self._target._on_ending(span)

    def on_end(self, span: Any) -> None:
        name = getattr(span, "name", "")
        # Filter out Phoenix internal server spans and endpoints
        if (
            name in ("POST /graphql", "GET /{path}")
            or name.startswith("fastapi.")
            or "/graphql" in name
        ):
            return
        attrs = getattr(span, "attributes", None) or {}
        if (
            attrs.get("http.route") == "/graphql"
            or attrs.get("url.path") == "/graphql"
            or (attrs.get("server.port") == 6006 and name.startswith(("POST", "GET")))
        ):
            return

        if hasattr(self._target, "on_end"):
            self._target.on_end(span)

    def force_flush(self, timeout_millis: int = 30000) -> bool:
        if hasattr(self._target, "force_flush"):
            return self._target.force_flush(timeout_millis)
        return True

    def shutdown(self) -> None:
        if hasattr(self._target, "shutdown"):
            self._target.shutdown()

    def __getattr__(self, name: str) -> Any:
        return getattr(self._target, name)


def setup_phoenix_tracer() -> bool:
    """
    Initializes Arize Phoenix in-process collector if enabled.
    Returns True if Phoenix is active, False otherwise.
    """
    global _PHOENIX_SESSION

    enabled = os.getenv("PHOENIX_ENABLED", "false").lower() in ("true", "1", "yes")
    if not enabled:
        return False

    if _PHOENIX_SESSION is not None:
        return True

    # Ensure UTF-8 output streams on Windows to prevent UnicodeEncodeError on emoji prints
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass
    if hasattr(sys.stderr, "reconfigure"):
        try:
            sys.stderr.reconfigure(encoding="utf-8")
        except Exception:
            pass

    try:
        import phoenix as px
        from phoenix.otel import register

        # Prevent exporter HTTP recursion and exclude internal server routes
        os.environ["OTEL_PYTHON_EXCLUDED_URLS"] = ".*graphql.*,.*v1/traces.*"
        os.environ["OTEL_PYTHON_FASTAPI_EXCLUDED_URLS"] = ".*graphql.*,.*v1/traces.*"

        # Use persistent working directory instead of temporary directory to avoid
        # Windows WinError 32 (file lock on SQLite phoenix.db during tempdir cleanup)
        _PHOENIX_SESSION = px.launch_app(use_temp_dir=False)

        # Register OpenTelemetry TracerProvider with Phoenix gRPC collector defaults
        tracer_provider = register(
            project_name="runwise",
            batch=True,
            auto_instrument=False,
            set_global_tracer_provider=True,
        )

        # Intercept and drop internal Phoenix server spans (POST /graphql, fastapi.*)
        if hasattr(tracer_provider, "_active_span_processor"):
            with tracer_provider._active_span_processor._lock:
                active = tracer_provider._active_span_processor._span_processors
                tracer_provider._active_span_processor._span_processors = tuple(
                    _FilterInternalSpansProcessor(p) for p in active
                )
                tracer_provider._default_processor = None

        print(f"\n🔭 Phoenix Observability Active: {_PHOENIX_SESSION.url}")
        return True
    except Exception as exc:
        print(f"⚠️ Failed to launch Phoenix session: {exc}")
        return False


def shutdown_phoenix_tracer() -> None:
    """
    Closes Phoenix session cleanly if active.
    """
    global _PHOENIX_SESSION
    if _PHOENIX_SESSION is not None:
        try:
            import phoenix as px
            px.close_app()
        except Exception:
            pass
        _PHOENIX_SESSION = None


class SpanHandle:
    """
    Mutable handle passed to the context block to allow enriching
    the active span with input/output, status, and custom attributes.
    """

    def __init__(self, span: Any = None) -> None:
        self.span = span

    def set_attribute(self, key: str, value: Any) -> None:
        if self.span is not None:
            self.span.set_attribute(key, str(value))

    def set_input(self, value: Any, mime_type: str = "text/plain") -> None:
        if self.span is not None and value is not None:
            val_str = json.dumps(value, ensure_ascii=False) if isinstance(value, (dict, list)) else str(value)
            self.span.set_attribute("input.value", val_str)
            if isinstance(value, (dict, list)):
                self.span.set_attribute("input.mime_type", "application/json")
            else:
                self.span.set_attribute("input.mime_type", mime_type)

    def set_output(self, value: Any, mime_type: str = "text/plain") -> None:
        if self.span is not None and value is not None:
            val_str = json.dumps(value, ensure_ascii=False) if isinstance(value, (dict, list)) else str(value)
            self.span.set_attribute("output.value", val_str)
            if isinstance(value, (dict, list)):
                self.span.set_attribute("output.mime_type", "application/json")
            else:
                self.span.set_attribute("output.mime_type", mime_type)

    def set_status_ok(self) -> None:
        if self.span is not None:
            try:
                from opentelemetry.trace import Status, StatusCode
                self.span.set_status(Status(StatusCode.OK))
            except Exception:
                pass

    def set_status_error(self, description: str = "") -> None:
        if self.span is not None:
            try:
                from opentelemetry.trace import Status, StatusCode
                self.span.set_status(Status(StatusCode.ERROR, description=description))
            except Exception:
                pass


@contextmanager
def trace_span(
    name: str,
    attributes: dict[str, Any] | None = None,
    span_kind: str | None = None,
    input_value: Any = None,
    output_value: Any = None,
) -> Generator[SpanHandle, None, None]:
    """
    Lightweight contextual trace span wrapper.
    Falls back gracefully to a no-op generator if OpenTelemetry/Phoenix is disabled.
    Enriches spans with OpenInference conventions for Phoenix UI visualization.
    """
    enabled = os.getenv("PHOENIX_ENABLED", "false").lower() in ("true", "1", "yes")
    if not enabled:
        yield SpanHandle(None)
        return

    try:
        from opentelemetry import trace
        from opentelemetry.trace import Status, StatusCode

        tracer = trace.get_tracer("runwise.agent")
        with tracer.start_as_current_span(name) as span:
            # Auto-infer OpenInference span kind if not provided
            kind = span_kind
            if not kind:
                if name.startswith("agent_run"):
                    kind = "AGENT"
                elif name.startswith("tool_dispatch") or name.startswith("tool_"):
                    kind = "TOOL"
                elif name.startswith("llm_completion") or name.startswith("llm_"):
                    kind = "LLM"
            if kind:
                span.set_attribute("openinference.span.kind", kind.upper())

            handle = SpanHandle(span)
            if input_value is not None:
                handle.set_input(input_value)
            if output_value is not None:
                handle.set_output(output_value)

            if attributes:
                for k, v in attributes.items():
                    span.set_attribute(k, str(v))

            try:
                yield handle
                handle.set_status_ok()
            except Exception as exc:
                handle.set_status_error(str(exc))
                raise
    except Exception:
        yield SpanHandle(None)
