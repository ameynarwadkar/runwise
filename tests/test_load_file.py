def test_customer_support_user_structure_via_locust_cli():
    """
    Validates locustfile syntax and task distribution via Locust's native CLI inspection.
    Note: Invoked via subprocess to prevent gevent monkeypatch conflicts with pytest under Python 3.14.
    """
    locustfile = PROJECT_ROOT / "ops" / "load" / "locustfile.py"
    assert locustfile.exists()

    cmd = [
        sys.executable,
        "-m",
        "locust",
        "-f",
        str(locustfile),
        "--show-task-ratio-json",
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, check=True)

    # Locate JSON output within locust log stream
    json_start = res.stdout.find("{")
    assert json_start != -1
    data = json.loads(res.stdout[json_start:])

    assert "CustomerSupportUser" in data["per_class"]
    tasks = data["per_class"]["CustomerSupportUser"]["tasks"]
    assert "agent_inquiry" in tasks
    assert "agent_mutation" in tasks
    assert "health_check" in tasks
    assert "ready_check" in tasks
    assert "metrics_scrape" in tasks


def test_agent_run_request_payload_validity():
    # Verify payloads generated by load test conform to Pydantic schemas
    payload_inquiry = {
        "session_id": "sess_test_123",
        "prompt": "Hi, what is the current shipping status of order ORD-101?",
        "task_id": "load_inquiry",
        "customer_id": "CUST-101",
    }
    validated_inquiry = AgentRunRequest(**payload_inquiry)
    assert validated_inquiry.session_id == "sess_test_123"
    assert "ORD-101" in validated_inquiry.prompt

    payload_mutation = {
        "session_id": "sess_test_456",
        "prompt": "Please cancel order ORD-102 immediately.",
        "task_id": "load_cancel",
        "customer_id": "CUST-102",
    }
    validated_mutation = AgentRunRequest(**payload_mutation)
    assert validated_mutation.customer_id == "CUST-102"


def test_format_benchmark_table(tmp_path: Path):
    dummy_csv = tmp_path / "test_stats.csv"
    dummy_csv.write_text(
        "Type,Name,Request Count,Failure Count,Median Response Time,Average Response Time,Min Response Time,Max Response Time,Average Content Size,Requests/s,Failures/s,50%,66%,75%,80%,90%,95%,98%,99%,99.9%,99.99%,100%\n"
        "GET,/healthz,100,0,2.1,2.5,1.0,8.0,50,20.0,0.0,2.0,2.0,3.0,3.0,4.0,5.0,6.0,7.0,8.0,8.0,8.0\n"
        ",Aggregated,100,0,2.1,2.5,1.0,8.0,50,20.0,0.0,2.0,2.0,3.0,3.0,4.0,5.0,6.0,7.0,8.0,8.0,8.0\n",
        encoding="utf-8",
    )
    records = parse_locust_stats(dummy_csv)
    assert len(records) == 2

    table = format_benchmark_table(records)
    assert "`/healthz`" in table
    assert "**Aggregated**" in table
    assert "100" in table
